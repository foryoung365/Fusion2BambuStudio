'use strict';
const assert=require('node:assert/strict');
const {math:M,Viewer}=require('../ui/viewer.js');
const near=(a,b)=>a.forEach((v,i)=>assert.ok(Math.abs(v-b[i])<1e-8,[a,b]));
const r=M.rz(90),matrix=M.modelMatrix(r,[10,20,30],2),p=[3,4,5];
near(M.point(matrix,p),[2,26,40]);
const ray=M.inverseRay(matrix,[2,26,60],[0,0,-1]);
near(ray.origin,[3,4,15]);near(ray.direction,[0,0,-.5]);
assert.equal(M.triangleHit([.2,.2,2],[0,0,-1],[0,0,0],[1,0,0],[0,1,0]),2);
assert.equal(M.triangleHit([2,2,2],[0,0,-1],[0,0,0],[1,0,0],[0,1,0]),null);
assert.equal(M.triangleHit([.2,.2,-2],[0,0,-1],[0,0,0],[1,0,0],[0,1,0]),null);
assert.ok(M.boxHit([0,0,10],[0,0,-1],[[-1,-1,-1],[1,1,1]]));
assert.ok(!M.boxHit([2,0,10],[0,0,-1],[[-1,-1,-1],[1,1,1]]));
const box=M.transformedBox([[0,0,0],[2,3,4]],matrix);
near(box[0],[4,20,30]);near(box[1],[10,24,38]);
const viewer=Object.create(Viewer.prototype);
viewer.canvas={clientWidth:800,clientHeight:600,getBoundingClientRect:()=>({left:0,top:0,width:800,height:600})};
viewer.camera={target:[7,8,9],span:200,yaw:-1,pitch:.7};viewer.invalidate=()=>{};
const worldPoint=[20,30,40],clip=M.point(viewer.view(),worldPoint);
const cursorRay=viewer.ray({clientX:(clip[0]+1)*400,clientY:(1-clip[1])*300});
near(M.cross(M.sub(worldPoint,cursorRay.origin),cursorRay.direction),[0,0,0]);
viewer.mode='face';viewer.drag={start:[400,300],last:[400,300],hit:{unit:'body'},button:0,moved:false};
viewer.move({clientX:400,clientY:100});
assert.ok(viewer.camera.pitch<0,'Must be able to orbit below a body to select its bottom faces');
assert.equal(viewer.drag.moved,true);
console.log('WebGL picking/matrix tests passed');
